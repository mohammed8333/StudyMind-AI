import fitz  # PyMuPDF

def create_sample_arabic_book(output_path="sample_physics_book.pdf"):
    doc = fitz.open()
    
    # Page 1: Newton's First Law
    page1 = doc.new_page()
    text_p1 = """
الفصل الأول: قوانين الحركة والقصور الذاتي

أولاً: مفهوم القوة والقصور الذاتي
القوة هي المؤثر الخارجي الذي يغير أو يحاول تغيير الحالة الحركية للجسم أو شكله.
يقاس مقدار القوة بوحدة النيوتن (N).

قانون نيوتن الأول (قانون القصور الذاتي):
يظل الجسم على حالته من سكون أو حركة منتظمة في خط مستقيم ما لم تؤثر عليه قوة محصلة خارجية تغير من حالته.

ملاحظة هامة:
القصور الذاتي هو خاصية مقاومة الجسم لتغيير حالته الحركية، وتعتمد هذه الخاصية بشكل طردي على كتلة الجسم.
    """.strip()
    page1.insert_text((50, 80), text_p1, fontsize=12)
    
    # Page 2: Newton's Second Law
    page2 = doc.new_page()
    text_p2 = """
الفصل الثاني: قانون نيوتن الثاني وكمية التحرك

أولاً: نص قانون نيوتن الثاني
القوة المحصلة المؤثرة على جسم تساوي المعدل الزمني للتغير في كمية تحركه، ويكون اتجاه التسارع في نفس اتجاه القوة.

الصيغة الرياضية:
F = m * a
حيث:
- F هي القوة المحصلة وتقاس بالنيوتن.
- m هي كتلة الجسم وتقاس بالكيلوجرام (kg).
- a هو التسارع أو العجلة وتقاس بـ (m/s^2).

ثانياً: كمية التحرك (Momentum)
كمية التحرك p هي حاصل ضرب كتلة الجسم في سرعته المتجهة (p = m * v).
وحدة قياس كمية التحرك هي kg.m/s.
    """.strip()
    page2.insert_text((50, 80), text_p2, fontsize=12)
    
    # Page 3: Newton's Third Law
    page3 = doc.new_page()
    text_p3 = """
الفصل الثالث: قانون نيوتن الثالث وقوة الفعل ورد الفعل

أولاً: نص قانون نيوتن الثالث
لكل قوة فعل قوة رد فعل مساوية لها في المقدار ومضادة لها في الاتجاه، وتؤثران في جسمين مختلفين.

خصائص قوى الفعل ورد الفعل:
1. تنشأ القوتان دائماً في أزواج متزامنة، ولا توجد قوة مفردة في الكون.
2. الفعل ورد الفعل لا يحدثان اتزاناً لأنهما تؤثران على جسمين مختلفين.
3. هما من نفس النوع (تجاذب كتل، كهرومغناطيسية، تلامس).

تطبيقات هامة:
- حركة الصواريخ وانطلاقها للأعلى بسبب اندفاع الغازات للأسفل.
- السباحة ودفع الماء للخلف للتقدم للأمام.
    """.strip()
    page3.insert_text((50, 80), text_p3, fontsize=12)
    
    doc.save(output_path)
    doc.close()
    print(f"Sample Arabic book created successfully at: {output_path}")

if __name__ == "__main__":
    create_sample_arabic_book()
